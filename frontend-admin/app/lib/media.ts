// Абсолютный адрес медиафайла для <img>/<video>/ссылок.
//
// В БД и в ответах API поля картинок хранят ОТНОСИТЕЛЬНЫЙ путь
// «/media/<файл>» (без домена): одна и та же запись корректно открывается
// и локально, и на боевом домене. Браузеру относительный путь пришлось бы
// разрешать от адреса АДМИНКИ (:3001), где медиа нет, — отсюда «битые»
// картинки. Поэтому дописываем домен API.
//
// Абсолютные URL старого формата (http://localhost:8000/media/…) в базе
// ещё могут встречаться — такие значения отдаём как есть.

import { API } from "./api";

/** «/media/x.webp» → «<API>/media/x.webp»; http(s)-адрес — без изменений. */
export function mediaUrl(v?: string | null): string | null {
  if (!v) return null;
  const s = v.trim();
  if (s === "") return null;
  if (s.startsWith("http")) return s; // абсолютный URL — как есть
  // Протокол-относительный адрес и inline-данные домена не требуют.
  if (s.startsWith("//") || s.startsWith("data:") || s.startsWith("blob:")) {
    return s;
  }
  if (s.startsWith("/")) return `${API}${s}`;
  // Неожиданный формат (без ведущего слэша) не «чиним» вслепую: пусть
  // значение будет видно как есть, чем превратится в чужой адрес.
  return s;
}
